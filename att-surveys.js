// كل عبارة/سؤال يأخذ معرّفاً ثابتاً تُحفظ به الإجابات
function tplQuestions(tpl){
  var out=[];
  tpl.blocks.forEach(function(b,bi){
    if(b.type==='likert') b.items.forEach(function(it,ii){
      var o=typeof it==='string'?{t:it}:it;
      out.push({id:'L'+bi+'_'+ii,type:'likert',t:o.t,rev:!!o.rev,scale:b.scale,block:bi,blockTitle:b.title||''});
    });
    else out.push({id:b.id,type:b.type,t:b.label,opts:b.opts,other:b.other,req:b.req,block:bi});
  });
  return out;
}
